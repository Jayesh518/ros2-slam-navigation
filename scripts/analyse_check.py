#!/usr/bin/env python3
"""Compare the plan-flip guard (`recovery`) with the baseline in world B, as fixed in docs/protocol.md changes (n) and (o).

Two comparisons, both paired by start/goal pair and both suggestive (20 pairs each):
  original pairs  results/trials/{baseline,recovery}_world_b.csv     (the pairs the guard thresholds were chosen on)
  fresh pairs     results/check/{baseline,recovery}_world_b.csv      (independent check, pairs k01 to k20)
Also the guard trigger counts for every world of the main run. Writes results/check/check_summary.md.
Usage: PYTHONPATH=src/nav_study_trials /usr/bin/python3 scripts/analyse_check.py
"""
import glob
from pathlib import Path

import pandas as pd

from nav_study_trials import analysis

ROOT = Path(__file__).resolve().parents[1]


def compare(label, base_csv, rec_csv):
    b = pd.read_csv(base_csv).query("valid == 1").set_index("pair")
    r = pd.read_csv(rec_csv).query("valid == 1").set_index("pair")
    idx = b.index.intersection(r.index)
    d = (r.loc[idx, "success"] - b.loc[idx, "success"]).to_numpy()
    s = analysis.decide_success(d)
    only_r, only_b = int((d > 0).sum()), int((d < 0).sum())
    both = [i for i in idx if r.loc[i, "success"] == 1 and b.loc[i, "success"] == 1]
    out = [f"### {label}", "",
           f"- pairs compared: {len(idx)}; baseline solved {int(b.loc[idx, 'success'].sum())}, recovery solved {int(r.loc[idx, 'success'].sum())}",
           f"- only recovery solved: {only_r} ({', '.join(i for i in idx if r.loc[i, 'success'] > b.loc[i, 'success']) or 'none'}); "
           f"only baseline solved: {only_b} ({', '.join(i for i in idx if r.loc[i, 'success'] < b.loc[i, 'success']) or 'none'})",
           f"- success difference (recovery minus baseline): {s['mean_diff']:+.2f}, 95% bootstrap interval {s['ci_lo']:+.2f} to {s['ci_hi']:+.2f}; rule of section 8: {s['verdict']} (suggestive, 20 pairs)"]
    if both:
        for col, name in (("time_s", "time s"), ("path_m", "path m")):
            dd = (r.loc[both, col] - b.loc[both, col]).to_numpy()
            c = analysis.decide_continuous(dd, b.loc[both, col].to_numpy())
            out.append(f"- {name} on the {len(both)} pairs both solved: {c['mean_diff']:+.1f} ({c['ci_lo']:+.1f} to {c['ci_hi']:+.1f}), baseline mean {c['baseline_mean']:.1f}")
    if "guard_triggers" in r:
        trig = r.loc[idx][r.loc[idx, "guard_triggers"] > 0]
        out.append(f"- guard triggered on {len(trig)} of {len(idx)} pairs ({', '.join(trig.index) or 'none'}); outcome on those: "
                   f"{int(trig.success.sum())} solved, {len(trig) - int(trig.success.sum())} not (baseline on the same pairs: {int(b.loc[trig.index, 'success'].sum()) if len(trig) else 0} solved)")
    return out


md = ["# Plan-flip guard against the baseline in world B (generated by scripts/analyse_check.py; do not edit)", ""]
pairs = [("Original 20 pairs (main run; thresholds were chosen on these pairs)", "results/trials/baseline_world_b.csv", "results/trials/recovery_world_b.csv"),
         ("Fresh 20 pairs (independent check, protocol change (o))", "results/check/baseline_world_b.csv", "results/check/recovery_world_b.csv")]
for label, bc, rc in pairs:
    if (ROOT / bc).exists() and (ROOT / rc).exists():
        md += compare(label, ROOT / bc, ROOT / rc) + [""]
    else:
        md += [f"### {label}", "", "not run yet", ""]
md += ["### Guard triggers and outcome in every world of the main run", "", "| world | trials | trials with a trigger | successes | median time s (successes) |", "|---|---|---|---|---|"]
for f in sorted(glob.glob(str(ROOT / "results/trials/recovery_world_*.csv"))):
    r = pd.read_csv(f).query("valid == 1")
    md.append(f"| {Path(f).stem.replace('recovery_', '')} | {len(r)} | {int((r.guard_triggers > 0).sum())} | {int(r.success.sum())} | {r[r.success == 1].time_s.median():.1f} |")
(ROOT / "results/check").mkdir(parents=True, exist_ok=True)
(ROOT / "results/check/check_summary.md").write_text("\n".join(md) + "\n")
print("\n".join(md))
