#!/usr/bin/env python3
"""Generate the three study worlds (protocol section 4: A1 open room, B1 office, C1 pillar grid) as Gazebo SDF.

Usage: python3 scripts/make_worlds.py    -> writes src/nav_study_bringup/worlds/world_{a,b,c}.sdf
All worlds share the same header (physics, systems, light, ground), so only the geometry differs between trials.
Walls and obstacles are 0.5 m high so the LiDAR plane (0.181 m) hits them. Layout numbers are in the dicts below.
"""
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "src/nav_study_bringup/worlds"
H = 0.5  # obstacle height
T = 0.1  # wall thickness

HEADER = """<?xml version="1.0"?>
<!-- {title}. Generated by scripts/make_worlds.py; edit the script, not this file. -->
<sdf version="1.8">
  <world name="default">
    <physics name="3ms" type="ode">
      <max_step_size>0.003</max_step_size>
      <real_time_factor>1</real_time_factor>
    </physics>
    <plugin filename="gz-sim-physics-system" name="gz::sim::systems::Physics"/>
    <plugin filename="gz-sim-user-commands-system" name="gz::sim::systems::UserCommands"/>
    <plugin filename="gz-sim-scene-broadcaster-system" name="gz::sim::systems::SceneBroadcaster"/>
    <plugin filename="gz-sim-sensors-system" name="gz::sim::systems::Sensors"><render_engine>ogre2</render_engine></plugin>
    <plugin filename="gz-sim-imu-system" name="gz::sim::systems::Imu"/>
    <plugin filename="gz-sim-contact-system" name="gz::sim::systems::Contact"/>
    <scene><shadows>false</shadows></scene>
    <light name="sun" type="directional">
      <cast_shadows>false</cast_shadows>
      <pose>0 0 10 0 0 0</pose>
      <diffuse>0.8 0.8 0.8 1</diffuse>
      <specular>0.2 0.2 0.2 1</specular>
      <direction>-0.5 0.1 -0.9</direction>
    </light>
    <model name="ground_plane">
      <static>true</static>
      <link name="link">
        <collision name="collision"><geometry><plane><normal>0 0 1</normal><size>100 100</size></plane></geometry></collision>
        <visual name="visual">
          <geometry><plane><normal>0 0 1</normal><size>100 100</size></plane></geometry>
          <material><ambient>0.8 0.8 0.8 1</ambient><diffuse>0.8 0.8 0.8 1</diffuse></material>
        </visual>
      </link>
    </model>
"""
FOOTER = "  </world>\n</sdf>\n"


def box(name, cx, cy, sx, sy, color="0.6 0.5 0.4 1"):
    return (f'        <collision name="{name}"><pose>{cx:.3f} {cy:.3f} {H/2} 0 0 0</pose><geometry><box><size>{sx:.3f} {sy:.3f} {H}</size></box></geometry></collision>\n'
            f'        <visual name="{name}_v"><pose>{cx:.3f} {cy:.3f} {H/2} 0 0 0</pose><geometry><box><size>{sx:.3f} {sy:.3f} {H}</size></box></geometry><material><diffuse>{color}</diffuse></material></visual>\n')


def cyl(name, cx, cy, r, color="0.3 0.5 0.8 1"):
    return (f'        <collision name="{name}"><pose>{cx:.3f} {cy:.3f} {H/2} 0 0 0</pose><geometry><cylinder><radius>{r}</radius><length>{H}</length></cylinder></geometry></collision>\n'
            f'        <visual name="{name}_v"><pose>{cx:.3f} {cy:.3f} {H/2} 0 0 0</pose><geometry><cylinder><radius>{r}</radius><length>{H}</length></cylinder></geometry><material><diffuse>{color}</diffuse></material></visual>\n')


def wall_x(name, x0, x1, y):
    """Wall along x from x0 to x1 at height y."""
    return box(name, (x0 + x1) / 2, y, abs(x1 - x0) + T, T)


def wall_y(name, y0, y1, x):
    return box(name, x, (y0 + y1) / 2, T, abs(y1 - y0) + T)


def model(name, body):
    return f'    <model name="{name}">\n      <static>true</static>\n      <link name="link">\n{body}      </link>\n    </model>\n'


def room(hx, hy):
    return (wall_x("north", -hx, hx, hy) + wall_x("south", -hx, hx, -hy)
            + wall_y("east", -hy, hy, hx) + wall_y("west", -hy, hy, -hx))


def world_a():
    """A1: open room 10 x 10 m with 4 obstacles, no inner walls."""
    b = room(5, 5)
    obstacles = (box("box1", -1.5, 1.5, 0.6, 0.6, "0.3 0.5 0.8 1") + box("box2", 2.0, -1.5, 0.8, 0.5, "0.3 0.5 0.8 1")
                 + cyl("cyl1", -2.0, -2.5, 0.3) + box("box3", 1.5, 2.5, 0.5, 0.5, "0.3 0.5 0.8 1"))
    return model("walls", b) + model("obstacles", obstacles)


def world_b():
    """B1: office 16 x 10 m. Corridor 1.5 m wide along x (|y| < 0.75), four rooms, 1 m doorways at x = -4 and x = 4."""
    hx, hy, c = 8.0, 5.0, 0.75
    b = room(hx, hy)
    for side, y in (("n", c), ("s", -c)):
        b += wall_x(f"corridor_{side}1", -hx, -4.5, y) + wall_x(f"corridor_{side}2", -3.5, 3.5, y) + wall_x(f"corridor_{side}3", 4.5, hx, y)
    b += wall_y("divider_n", c, hy, 0.0) + wall_y("divider_s", -hy, -c, 0.0)
    furniture = (box("desk1", -5.5, 3.0, 1.2, 0.6, "0.5 0.35 0.2 1") + box("desk2", 5.5, -3.0, 1.2, 0.6, "0.5 0.35 0.2 1")
                 + box("cabinet1", 2.0, 4.4, 0.8, 0.4, "0.5 0.35 0.2 1") + box("cabinet2", -2.0, -4.4, 0.8, 0.4, "0.5 0.35 0.2 1"))
    return model("walls", b) + model("furniture", furniture)


def world_c():
    """C1: 12 x 12 m room with a 4 x 4 grid of identical pillars (symmetric, feature-poor), spacing 2.5 m, radius 0.25 m."""
    b = room(6, 6)
    pillars = ""
    coords = (-3.75, -1.25, 1.25, 3.75)
    for i, x in enumerate(coords):
        for j, y in enumerate(coords):
            pillars += cyl(f"pillar_{i}{j}", x, y, 0.25, "0.7 0.7 0.7 1")
    return model("walls", b) + model("pillars", pillars)


for fname, title, fn in (("world_a", "World A1: open room with four obstacles", world_a),
                         ("world_b", "World B1: office with corridor, four rooms and doorways", world_b),
                         ("world_c", "World C1: symmetric 4 x 4 pillar grid", world_c)):
    (OUT / f"{fname}.sdf").write_text(HEADER.format(title=title) + fn() + FOOTER)
    print("wrote", OUT / f"{fname}.sdf")
