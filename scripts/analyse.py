#!/usr/bin/env python3
"""Summarise the study trials (results/trials/*.csv) as in docs/protocol.md section 8.

Writes: results/summary.csv, results/summary.md                    per configuration and world (and pooled)
        results/paired_vs_baseline.csv, results/paired_vs_baseline.md   paired comparison of each configuration with the baseline
        docs/figures/success-by-config.png                        success rate with Wilson 95 percent intervals
Usage: PYTHONPATH=src/nav_study_trials /usr/bin/python3 scripts/analyse.py
Invalid trials (valid = 0, reset not verified) are excluded from every rate and reported as a count.
"""
import glob
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

from nav_study_trials import analysis, metrics

ROOT = Path(__file__).resolve().parents[1]
WORLDS = ["world_a", "world_b", "world_c", "world_d"]
POOLED = {"A-C": ["world_a", "world_b", "world_c"], "A-D": ["world_a", "world_b", "world_c", "world_d"]}  # A-C = original design; D added later (change log (l))
ORDER = ["baseline", "smac2d", "thetastar", "dwb", "rpp", "recovery"]

frames = [pd.read_csv(f) for f in sorted(glob.glob(str(ROOT / "results/trials/*.csv")))]
if not frames:
    raise SystemExit("no trial files in results/trials/")
df = pd.concat(frames, ignore_index=True)
df["valid"] = df["valid"].fillna(1).astype(int)
configs = [c for c in ORDER if c in set(df.config)]


def summarise(sub):
    ok = sub[sub.valid == 1]
    n, s = len(ok), int(ok.success.sum())
    lo, hi = metrics.wilson_interval(s, n)
    won = ok[ok.success == 1]
    return {"n_trials": len(sub), "n_invalid": int((sub.valid == 0).sum()), "n_valid": n, "successes": s,
            "success_rate": s / n if n else np.nan, "wilson_lo": lo, "wilson_hi": hi,
            "median_time_s": won.time_s.median(), "median_path_m": won.path_m.median(),
            "collisions_per_trial": ok.collisions.mean(), "trials_with_collision": int((ok.collisions > 0).sum()),
            "recoveries_per_trial": ok.recovery_events.mean(), "mean_loc_err_m": ok.loc_err_mean_m.mean(),
            "loc_failures": int(ok.loc_failure.sum())}


rows = []
for c in configs:
    for w in WORLDS + list(POOLED):
        sub = df[(df.config == c) & (df.world.isin(POOLED[w]) if w in POOLED else (df.world == w))]
        if len(sub):
            rows.append({"config": c, "world": w, **summarise(sub)})
summary = pd.DataFrame(rows)
summary.to_csv(ROOT / "results/summary.csv", index=False, float_format="%.4g")

md = ["# Trial summary (generated by scripts/analyse.py; do not edit)\n",
      "Success rate with Wilson 95% interval; time and path are medians over successful trials only; invalid trials excluded.\n",
      "| config | world | valid/total | successes | success rate (95% CI) | median time s | median path m | collisions/trial | recoveries/trial | mean loc. error m |",
      "|---|---|---|---|---|---|---|---|---|---|"]
for _, r in summary.iterrows():
    md.append(f"| {r.config} | {r.world} | {r.n_valid}/{r.n_trials} | {r.successes} | {r.success_rate:.2f} ({r.wilson_lo:.2f} to {r.wilson_hi:.2f}) | "
              f"{r.median_time_s:.1f} | {r.median_path_m:.2f} | {r.collisions_per_trial:.2f} | {r.recoveries_per_trial:.2f} | {r.mean_loc_err_m:.3f} |")
fail = df[(df.valid == 1) & (df.success == 0)].groupby(["config", "world", "failure_reason"]).size()
if len(fail):
    md += ["", "## Failure reasons (valid trials)", "", "| config | world | reason | count |", "|---|---|---|---|"]
    md += [f"| {c} | {w} | {r} | {n} |" for (c, w, r), n in fail.items()]
(ROOT / "results/summary.md").write_text("\n".join(md) + "\n")

# paired comparison against the baseline, by pair (protocol section 8)
paired_rows = []
if "baseline" in configs:
    base = df[(df.config == "baseline") & (df.valid == 1)].set_index(["world", "pair"])
    for c in [x for x in configs if x != "baseline"]:
        cur = df[(df.config == c) & (df.valid == 1)].set_index(["world", "pair"])
        for scope in WORLDS + list(POOLED):
            idx = [i for i in cur.index.intersection(base.index) if (i[0] in POOLED[scope] if scope in POOLED else i[0] == scope)]
            if not idx:
                continue
            d_succ = (cur.loc[idx, "success"] - base.loc[idx, "success"]).to_numpy()
            both = [i for i in idx if cur.loc[i, "success"] == 1 and base.loc[i, "success"] == 1]
            res = {"config": c, "scope": scope, "label": ("primary, original design" if scope == "A-C" else "primary, with post-hoc world D") if scope in POOLED else ("suggestive (per world; D is post-hoc)" if scope == "world_d" else "suggestive (per world)")}
            r = analysis.decide_success(d_succ)
            res.update({"success_diff": r["mean_diff"], "success_lo": r["ci_lo"], "success_hi": r["ci_hi"], "n_pairs": r["n_pairs"], "success_verdict": r["verdict"]})
            for col in ("time_s", "path_m"):
                dd = (cur.loc[both, col] - base.loc[both, col]).to_numpy()
                rc = analysis.decide_continuous(dd, base.loc[both, col].to_numpy())
                res.update({f"{col}_diff": rc["mean_diff"], f"{col}_lo": rc["ci_lo"], f"{col}_hi": rc["ci_hi"], f"{col}_n": rc["n_pairs"], f"{col}_verdict": rc["verdict"]})
            paired_rows.append(res)
    if paired_rows:
        pr = pd.DataFrame(paired_rows)
        pr.to_csv(ROOT / "results/paired_vs_baseline.csv", index=False, float_format="%.4g")
        pm = ["# Paired comparison with the baseline (generated by scripts/analyse.py; do not edit)\n",
              "Unit = start/goal pair. Success: mean paired difference with 95% bootstrap interval over pairs; verdict by the pre-registered rule "
              "(at least 10 points and interval excludes 0). Time/path: pairs where both succeeded; rule: interval excludes 0 and size above 5% of baseline. "
              "Per-world rows are suggestive only (20 pairs). A-C is the original design; A-D includes the post-hoc world D.\n",
              "| config | scope | n pairs | success diff (95% CI) | verdict | time diff s (95% CI), n | verdict | path diff m (95% CI), n | verdict |", "|---|---|---|---|---|---|---|---|---|"]
        for _, r in pr.iterrows():
            pm.append(f"| {r.config} | {r.scope} | {r.n_pairs} | {r.success_diff:+.2f} ({r.success_lo:+.2f} to {r.success_hi:+.2f}) | {r.success_verdict} | "
                      f"{r.time_s_diff:+.1f} ({r.time_s_lo:+.1f} to {r.time_s_hi:+.1f}), {r.time_s_n} | {r.time_s_verdict} | "
                      f"{r.path_m_diff:+.2f} ({r.path_m_lo:+.2f} to {r.path_m_hi:+.2f}), {r.path_m_n} | {r.path_m_verdict} |")
        (ROOT / "results/paired_vs_baseline.md").write_text("\n".join(pm) + "\n")

# figure: success rate by configuration and world
fig, ax = plt.subplots(figsize=(9, 4.6))
width = 0.8 / len(configs)
colors = {"world_a": "#4c78a8", "world_b": "#f58518", "world_c": "#54a24b", "world_d": "#b279a2", "A-D": "#444444"}
for k, w in enumerate(WORLDS + ["A-D"]):
    xs, ys, err_lo, err_hi = [], [], [], []
    for i, c in enumerate(configs):
        r = summary[(summary.config == c) & (summary.world == w)]
        if len(r):
            r = r.iloc[0]
            xs.append(i + (k - 2.0) * 0.16); ys.append(r.success_rate)
            err_lo.append(r.success_rate - r.wilson_lo); err_hi.append(r.wilson_hi - r.success_rate)
    ax.bar(xs, ys, width=0.15, yerr=[err_lo, err_hi], capsize=3, color=colors[w], label=w.replace("world_", "world ").upper() if w.startswith("world") else "all four worlds")
ax.set_xticks(range(len(configs))); ax.set_xticklabels(configs)
ax.set_ylim(0, 1.05); ax.set_ylabel("success rate (Wilson 95% interval)")
ax.set_title("Navigation success by configuration and world (20 pairs per world, 1 trial per pair; world D added after the baseline)", fontsize=10)
ax.legend(ncol=5, loc="lower left", fontsize=8); ax.grid(axis="y", alpha=0.3)
fig.tight_layout()
fig.savefig(ROOT / "docs/figures/success-by-config.png", dpi=110)
print(f"wrote results/summary.csv/.md, {'results/paired_vs_baseline.csv/.md, ' if paired_rows else ''}docs/figures/success-by-config.png")
